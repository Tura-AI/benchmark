import { expect, test } from '@playwright/test'

test('storefront search, preview, cart, checkout, and analytics work', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByText('POWERPROMPT Gallery').first()).toBeVisible()
  await page.locator('.dock-btn[aria-label="Search"]').click()
  await page.getByLabel('Search prompts').fill('cover')
  await expect(page.getByText('Magazine Cover Maker').first()).toBeVisible()
  await page.getByRole('button', { name: 'Preview Magazine Cover Maker' }).click()
  await expect(page.locator('.lb-card h2', { hasText: 'Magazine Cover Maker' })).toBeVisible()
  await page.getByRole('button', { name: /Add to cart|Get it free/ }).click()
  await expect(page.getByText(/Added:/)).toBeVisible()
  await page.getByRole('link', { name: 'Cart' }).click()
  await expect(page.getByRole('heading', { name: 'Cart and checkout' })).toBeVisible()
  await expect(page.getByText('Order summary')).toBeVisible()
  await page.getByRole('button', { name: 'Simulate checkout' }).click()
  await expect(page.getByText(/Checkout complete/)).toBeVisible()
  await page.getByRole('link', { name: 'Continue shopping' }).click()
  await page.getByRole('link', { name: 'Analytics', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Sales analytics' })).toBeVisible()
  await expect(page.getByText('Creator revenue').first()).toBeVisible()
})

test('mobile drawer and dock expose marketplace actions', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await page.getByRole('button', { name: 'Menu' }).click()
  await expect(page.getByLabel('Sidebar')).toBeVisible()
  await page.getByRole('button', { name: 'Favorites', exact: true }).last().click()
  await expect(page.getByText('POWERPROMPT Gallery').first()).toBeVisible()
  await page.getByRole('link', { name: 'Cart' }).click()
  await expect(page.getByRole('heading', { name: 'Cart and checkout' })).toBeVisible()
})
