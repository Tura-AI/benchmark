import { chromium } from 'playwright'
const browser = await chromium.launch()
const page = await browser.newPage()
page.on('console', msg => console.log('console', msg.type(), msg.text()))
page.on('pageerror', err => console.log('pageerror', err.message))
await page.goto('http://127.0.0.1:3000/prompt/cinematic-still-35mm')
console.log('url', page.url())
console.log('heading', await page.getByRole('heading', { name: 'Cinematic Still, 35mm' }).isVisible())
console.log('buttons', JSON.stringify(await page.getByRole('button').evaluateAll(bs => bs.map(b => b.textContent))))
await page.getByRole('button', { name: 'Add to Cart' }).click()
await page.waitForTimeout(1000)
console.log('bodyHasAdded', (await page.locator('body').textContent())?.includes('Added to Cart'))
console.log('status', JSON.stringify(await page.locator('.status').evaluateAll(xs => xs.map(x => x.textContent))))
await browser.close()
