import { chromium, devices } from '@playwright/test';
const browser = await chromium.launch();
const context = await browser.newContext(devices['Pixel 5']);
const page = await context.newPage();
page.on('console', msg => console.log('console', msg.type(), msg.text()));
page.on('pageerror', err => console.log('pageerror', err.message));
await page.goto('http://127.0.0.1:3014/', { waitUntil: 'networkidle' });
console.log('menu visible', await page.getByRole('button', { name: 'Menu' }).isVisible());
await page.getByRole('button', { name: 'Menu' }).click();
await page.waitForTimeout(300);
console.log('drawer count', await page.locator('.mobile-drawer.open').count());
await page.keyboard.press('Escape').catch(()=>{});
await page.goto('http://127.0.0.1:3014/', { waitUntil: 'networkidle' });
await page.getByRole('button', { name: /Reveal search/ }).click();
await page.getByPlaceholder(/Search prompts/).fill('cold email');
console.log('target count', await page.getByRole('button', { name: 'Open The Cold-Email Closer' }).count());
console.log('target box', await page.getByRole('button', { name: 'Open The Cold-Email Closer' }).boundingBox());
await page.getByRole('button', { name: 'Open The Cold-Email Closer' }).click();
await page.waitForTimeout(300);
console.log('dialog count', await page.getByRole('dialog').count());
await browser.close();
