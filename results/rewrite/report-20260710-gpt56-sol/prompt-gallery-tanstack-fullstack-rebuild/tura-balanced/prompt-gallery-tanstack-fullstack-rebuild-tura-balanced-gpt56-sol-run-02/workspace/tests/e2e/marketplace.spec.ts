  test.skip(!isMobile, 'Mobile-only navigation contract')
  await page.goto('/')
  await page.getByRole('button', { name: 'Open menu' }).click()
  await expect(page.getByRole('complementary', { name: 'Marketplace navigation' })).toBeVisible()
