import { expect, test } from '@playwright/test'

test('storefront search, favorite, cart, and checkout flow', async ({ page }) => {
  const errors: string[] = []
  page.on('console', (msg) => msg.type() === 'error' && errors.push(msg.text()))
  await page.goto('/')
  await expect(page.getByText('POWERPROMPT').first()).toBeVisible()
  await expect(page.locator('.prompt-card')).toHaveCount(12)
  await page.screenshot({ path: `test-results/${test.info().project.name}-storefront.png`, fullPage: true })
  await page.getByRole('button', { name: 'Search' }).last().click()
  await page.getByLabel('Search prompts').fill('watercolor')
  await expect(page.locator('.prompt-card')).toHaveCount(1)
  await page.locator('.prompt-card').click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.screenshot({ path: `test-results/${test.info().project.name}-preview.png`, fullPage: true })
  await page.getByRole('link', { name: 'Full details' }).click()
  await expect(page.getByRole('heading', { name: 'Watercolor Cityscape', level: 1 })).toBeVisible()
  await page.screenshot({ path: `test-results/${test.info().project.name}-detail.png`, fullPage: true })
  await page.getByRole('button', { name: 'Saved', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Save', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Saved', exact: true })).toBeVisible()
  await page.getByRole('button', { name: /Add to cart|Get it free/ }).click()
  await page.getByLabel(/Cart, \d+ items/).click()
  await expect(page.getByRole('heading', { name: 'Cart' })).toBeVisible()
  await page.screenshot({ path: `test-results/${test.info().project.name}-cart.png`, fullPage: true })
  await page.getByRole('button', { name: 'Complete order' }).click()
  await expect(page.getByText('Your prompts are ready.')).toBeVisible()
  await page.screenshot({ path: `test-results/${test.info().project.name}-receipt.png`, fullPage: true })
  expect(errors).toEqual([])
})

