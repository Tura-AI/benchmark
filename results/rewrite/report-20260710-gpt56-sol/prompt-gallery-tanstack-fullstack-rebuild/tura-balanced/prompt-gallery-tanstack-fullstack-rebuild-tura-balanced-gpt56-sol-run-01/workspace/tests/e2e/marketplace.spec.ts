import { expect, test } from '@playwright/test'

test.beforeEach(async ({ page }) => {
  page.on('pageerror', (error) => console.log(`PAGE_ERROR: ${error.message}`))
  page.on('requestfailed', (request) => console.log(`REQUEST_FAILED: ${request.url()} ${request.failure()?.errorText}`))
  page.on('console', (message) => { if (message.type() === 'error') console.log(`CONSOLE_ERROR: ${message.text()}`) })
  page.on('response', (response) => { if (response.url().includes('_serverFn')) console.log(`SERVER_FN: ${response.status()} ${response.url()}`) })
})

test('storefront filters, previews, favorites, and cart work', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByText('POWERPROMPT').first()).toBeVisible()
  await expect(page.locator('.prompt-card')).toHaveCount(22)
  await page.screenshot({ path: 'artifacts/storefront-desktop.png', fullPage: true })
  await page.getByRole('button', { name: 'Claude', exact: true }).click()
  console.log(`CLAUDE_CLASS: ${await page.getByRole('button', { name: 'Claude', exact: true }).getAttribute('class')}`)
  await expect(page.locator('.prompt-card')).toHaveCount(5)
  await page.getByRole('button', { name: 'Search', exact: true }).first().click()
  await page.getByRole('textbox', { name: 'Search prompts' }).fill('meeting')
  await expect(page.locator('.prompt-card')).toHaveCount(1)
  await page.getByRole('button', { name: /Preview Meeting to Memo/ }).click()
  await expect(page.getByRole('dialog')).toContainText('Meeting to Memo')
  await page.screenshot({ path: 'artifacts/prompt-preview.png', fullPage: true })
  await page.getByRole('button', { name: /Save/ }).click()
  await page.getByRole('button', { name: /Add to cart/ }).click()
  await page.getByRole('button', { name: 'Close preview' }).click()
  await expect(page.getByRole('status')).toContainText('Collection updated')
  await page.goto('/prompt/101')
  await expect(page.getByRole('heading', { name: 'Meeting to Memo' })).toBeVisible()
  await expect(page.getByRole('button', { name: /Add to cart/ })).toBeVisible()
})

test('cart checkout and analytics routes expose complete flows', async ({ page }) => {
  await page.goto('/cart')
  await expect(page.getByRole('heading', { name: 'Your prompt stack' })).toBeVisible()
  if (await page.getByText('Your cart is empty').isVisible().catch(() => false)) {
    await page.goto('/')
    await page.locator('.prompt-card').first().hover()
    await page.locator('.prompt-card').first().getByRole('button', { name: /Add/ }).click()
    await page.goto('/cart')
  }
  await page.getByLabel('Email for receipt').fill('e2e@example.com')
  await page.getByRole('button', { name: /Complete checkout/ }).click()
  await expect(page.getByText('Order confirmed')).toBeVisible()
  await page.goto('/creator/analytics')
  await expect(page.getByRole('heading', { name: 'Sales, without the noise.' })).toBeVisible()
  await expect(page.getByText('Creator revenue')).toBeVisible()
  await page.screenshot({ path: 'artifacts/analytics-desktop.png', fullPage: true })
  const api = await page.request.get('/api/catalog?model=Flux&sort=popular')
  expect(api.ok()).toBeTruthy()
  expect((await api.json()).data.every((prompt: { model: string }) => prompt.model === 'Flux')).toBeTruthy()
})

test('mobile drawer and dock remain usable', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await page.getByRole('button', { name: 'Open menu' }).click()
  await expect(page.locator('.sidebar')).toHaveClass(/sidebar--open/)
  await expect(page.locator('.sidebar').getByRole('link', { name: /Creator analytics/ })).toBeVisible()
  await page.locator('.sidebar').getByRole('button', { name: 'Close menu' }).click()
  await expect(page.getByRole('navigation', { name: 'Quick actions' })).toBeVisible()
  await page.getByRole('button', { name: 'Search', exact: true }).last().click()
  await expect(page.getByRole('textbox', { name: 'Search prompts' })).toBeVisible()
  await page.screenshot({ path: 'artifacts/storefront-mobile.png', fullPage: true })
})
