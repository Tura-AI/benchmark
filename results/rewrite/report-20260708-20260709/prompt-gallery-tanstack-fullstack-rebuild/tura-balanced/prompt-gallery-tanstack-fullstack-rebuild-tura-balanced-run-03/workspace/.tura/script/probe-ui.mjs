import { chromium } from '@playwright/test';
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
page.on('console', msg => console.log('console', msg.type(), msg.text()));
page.on('pageerror', err => console.log('pageerror', err.message));
await page.goto('http://127.0.0.1:3013/', { waitUntil: 'networkidle' });
await page.getByRole('button', { name: /Reveal search/ }).click();
await page.getByPlaceholder(/Search prompts/).fill('cold email');
const target = page.getByRole('button', { name: 'Open The Cold-Email Closer' });
console.log('target count', await target.count(), 'visible', await target.isVisible());
console.log('target tag', await target.evaluate(el => `${el.tagName}:${el.getAttribute('class')}:${el.getAttribute('role')}:${el.getAttribute('aria-label')}`));
await target.click({ force: true });
await page.waitForTimeout(500);
console.log('after click dialog', await page.getByRole('dialog').count(), 'lb', await page.locator('.lb.open').count());
console.log('body has title', await page.locator('body').evaluate(el => el.textContent?.includes('The Cold-Email Closer')));
await browser.close();
