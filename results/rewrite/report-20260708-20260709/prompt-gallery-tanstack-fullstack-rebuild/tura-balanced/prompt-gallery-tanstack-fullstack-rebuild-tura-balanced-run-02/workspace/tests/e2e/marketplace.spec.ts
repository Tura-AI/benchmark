import { expect, test } from '@playwright/test'

test('storefront filter favorite cart and admin flows work', async ({ page }) => {
  await page.goto('/')
  await page.waitForLoadState('networkidle')
  await expect(page.getByText('POWERPROMPT').first()).toBeVisible()
  await expect(page.getByRole('link', { name: /GPT-4o/ })).toBeVisible()
  await page.getByRole('link', { name: /Claude/ }).click()
  await expect(page.getByText('Senior Code Reviewer')).toBeVisible()
  const firstTile = page.locator('.tile').nth(1)
  await firstTile.scrollIntoViewIfNeeded()
  await firstTile.hover()
  await firstTile.getByRole('button', { name: 'Save' }).dispatchEvent('click')
  await expect(page.getByRole('status')).toContainText(/Saved|Removed/)
  await firstTile.getByRole('button', { name: 'Add' }).dispatchEvent('click')
  await expect(page.getByRole('status')).toContainText('Added')
  await page.goto('/cart')
  await expect(page.getByRole('heading', { name: 'Cart' })).toBeVisible()
  await page.goto('/admin')
  await expect(page.getByRole('heading', { name: 'Creator analytics' })).toBeVisible()
  await expect(page.getByText('Category revenue')).toBeVisible()
})

test('mobile drawer opens navigation', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await page.waitForLoadState('networkidle')
  await page.getByRole('button', { name: 'Menu' }).click({ force: true })
  await expect(page.getByLabel('Marketplace navigation')).toBeVisible()
  await page.goto('/?favorites=true')
  await expect(page.getByText('Power prompts')).toBeVisible()
})
