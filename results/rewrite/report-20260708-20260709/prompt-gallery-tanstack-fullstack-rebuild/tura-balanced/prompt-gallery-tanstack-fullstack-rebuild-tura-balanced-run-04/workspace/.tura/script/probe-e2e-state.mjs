import { chromium, devices } from 'playwright';
const browser = await chromium.launch();
const page = await browser.newPage();
await page.goto('http://127.0.0.1:3000/', { waitUntil: 'networkidle' });
await page.getByRole('button', { name: 'GPT-4o' }).click();
await page.getByRole('button', { name: /Preview/ }).first().click();
await page.waitForTimeout(1000);
console.log('after filter preview dialogs', await page.getByRole('dialog').count(), page.url());
const mobile = await browser.newPage({ ...devices['Pixel 5'] });
await mobile.goto('http://127.0.0.1:3000/', { waitUntil: 'networkidle' });
const box = await mobile.getByLabel('Cart').boundingBox();
const computed = await mobile.locator('.dock').evaluate((el) => { const s=getComputedStyle(el); const r=el.getBoundingClientRect(); return { z:s.zIndex, position:s.position, transform:s.transform, left:r.left, top:r.top, width:r.width, height:r.height, display:s.display } });
const hit = await mobile.evaluate(({x,y}) => { const el=document.elementFromPoint(x,y); return el ? { tag: el.tagName, cls: el.getAttribute('class'), label: el.getAttribute('aria-label'), alt: el.getAttribute('alt') } : null }, { x: box.x + box.width / 2, y: box.y + box.height / 2 });
console.log('cartBox', box);
console.log('dock', computed);
console.log('hit', hit);
await browser.close();
